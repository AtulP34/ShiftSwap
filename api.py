@app.post("/api/register")
def register():
    data, missing = body("name", "email", "password")
    if missing:
        return error("Missing: " + ", ".join(missing))
 
    email = data["email"].strip().lower()  # so "Maya@X.com" and "maya@x.com" match
    if query("SELECT 1 FROM users WHERE email = ?", (email,), one=True):
        return error("Email already registered", 409)
 
    # Never store the real password, only a scrambled hash of it.
    user_id = execute(
        "INSERT INTO users (name, email, password_hash) VALUES (?, ?, ?)",
        (data["name"].strip(), email, generate_password_hash(data["password"])),
    )
    session["user_id"] = user_id  # log them in right away
    return jsonify({"id": user_id, "name": data["name"].strip()}), 201
 
 
@app.post("/api/login")
def login():
    data, missing = body("email", "password")
    if missing:
        return error("Missing: " + ", ".join(missing))
 
    user = query(
        "SELECT * FROM users WHERE email = ?",
        (data["email"].strip().lower(),),
        one=True,
    )
    # Same message for "no such user" and "wrong password" so attackers
    # can't use this to find out which emails exist.
    if user is None or not check_password_hash(user["password_hash"], data["password"]):
        return error("Invalid email or password", 401)
 
    session["user_id"] = user["id"]
    return jsonify({"id": user["id"], "name": user["name"]})
 
 
@app.post("/api/logout")
def logout():
    session.clear()  # forget who was logged in
    return jsonify({"ok": True})
 
 
